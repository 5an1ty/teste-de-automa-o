from typing import Protocol
from .models import Order

class SystemFailure(RuntimeError):
    """Perda de contexto: interromper lote e exigir avaliação humana."""

class SapInterface(Protocol):
    def buscar_ordem(self, numero: str) -> bool: ...
    def ler_dados_ordem(self) -> Order: ...
    def confirmar_contexto(self, numero: str) -> bool: ...
    def abrir_impressao(self, numero: str) -> bool: ...
    def enviar_impressao(self) -> None: ...
    def confirmar_envio(self) -> bool: ...
    def confirmar_impressao_fisica(self) -> bool: ...

class RealSap:
    def __init__(self, *args, **kwargs):
        raise SystemFailure("Integração real bloqueada: capturar seletores e homologar adaptador autorizado; consulte docs/POWER_AUTOMATE.md")
